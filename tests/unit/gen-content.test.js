import { describe, it, expect, beforeAll, afterAll } from 'vitest';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import { bundle, generateAll, BUNDLES, HEADER, HTML_BUNDLES } from '../../scripts/gen-content.mjs';

// E1-T14 (D6): ES modules from src/page/ glued into classic IIFE bundles. Fixtures live in
// tests/fixtures/modules/; the real entries come with T15.
const FIXTURES = fileURLToPath(new URL('../fixtures/modules/', import.meta.url));
const sha256 = (text) => createHash('sha256').update(text).digest('hex');
// ESLint tests only (see below).
const ESLINT_TIMEOUT_MS = 60000;

// Runs a bundle in a fresh context; returns what it pushed to __out and the keys left on the global.
function run(code) {
  const ctx = vm.createContext({ __out: [] });
  new vm.Script(code).runInContext(ctx);
  const out = ctx.__out;
  delete ctx.__out;
  return { out, keys: Object.keys(ctx) };
}

let tmp;
beforeAll(async () => {
  tmp = await mkdtemp(join(tmpdir(), 'pds-gen-'));
});
afterAll(async () => {
  await rm(tmp, { recursive: true, force: true });
});

describe('bundle', () => {
  const graph = () => bundle({ entry: 'entry.js', srcDir: join(FIXTURES, 'graph') });

  it('bundles modules in dependency order, each once', () => {
    const code = graph();
    const order = [...code.matchAll(/^\/\/ module: (.+)$/gm)].map((m) => m[1]);
    expect(order).toEqual(['log.js', 'counter.js', 'util.js', 'constants.js', 'reexport.js', 'side-effect.js', 'entry.js']);
    expect(run(code).out).toEqual(['util loaded', 'side effect', 'add 2', 'count=2 twice=4 triple=3 v=9.9.9']);
  });

  it('strips imports and export keywords; output has no import/export tokens', () => {
    const code = graph();
    expect(code).not.toMatch(/^\s*(import|export)\b/m);
    expect(code).not.toMatch(/\bimport\s*\(/);
  });

  it('starts with the GENERATED header and use strict, LF only', () => {
    const code = graph();
    expect(HEADER).toBe('// GENERATED by scripts/gen-content.mjs — do not edit');
    expect(code.startsWith(`${HEADER}\n(function () {\n  'use strict';\n`)).toBe(true);
    expect(code.endsWith('})();\n')).toBe(true);
    expect(code).not.toContain('\r');
  });

  it('module code runs in strict mode', async () => {
    const dir = join(tmp, 'strict');
    await mkdir(dir, { recursive: true });
    await writeFile(join(dir, 'entry.js'), 'undeclared = 1;\n');
    const code = bundle({ entry: 'entry.js', srcDir: dir });
    expect(() => new vm.Script(code).runInContext(vm.createContext({}))).toThrow(/undeclared is not defined/);
  });

  it('accepts a custom banner', () => {
    const code = bundle({ entry: 'entry.js', srcDir: join(FIXTURES, 'graph'), banner: '// custom' });
    expect(code.startsWith('// custom\n(function () {')).toBe(true);
  });

  it('wraps in IIFE: top-level names do not leak to global', () => {
    expect(run(graph()).keys).toEqual([]);
  });

  it('keeps same-named locals of different modules apart', () => {
    const code = bundle({ entry: 'entry.js', srcDir: join(FIXTURES, 'collision') });
    expect(run(code).out).toEqual(['from a', 'from b']);
  });

  it('is deterministic (two runs give identical SHA-256)', () => {
    expect(sha256(graph())).toBe(sha256(graph()));
  });

  it('normalizes CRLF sources to the same output as LF', async () => {
    const dir = join(tmp, 'crlf');
    await mkdir(dir, { recursive: true });
    for (const name of ['entry.js', 'a.js', 'b.js']) {
      const src = await readFile(join(FIXTURES, 'collision', name), 'utf8');
      await writeFile(join(dir, name), src.replace(/\r?\n/g, '\r\n'));
    }
    const crlf = bundle({ entry: 'entry.js', srcDir: dir });
    const lf = bundle({ entry: 'entry.js', srcDir: join(FIXTURES, 'collision') });
    expect(sha256(crlf)).toBe(sha256(lf));
  });

  it('writes outFile when given', async () => {
    const outFile = join(tmp, 'out', 'bundle.js');
    const code = bundle({ entry: 'entry.js', srcDir: join(FIXTURES, 'graph'), outFile });
    expect(await readFile(outFile, 'utf8')).toBe(code);
  });

  it('throws on a cycle, naming the modules', () => {
    expect(() => bundle({ entry: 'entry.js', srcDir: join(FIXTURES, 'cycle') }))
      .toThrow(/Import cycle: entry\.js -> a\.js -> b\.js -> a\.js/);
  });

  it('throws on bare specifier / dynamic import / multi-line import / require', () => {
    const errors = join(FIXTURES, 'errors');
    expect(() => bundle({ entry: 'bare.js', srcDir: errors })).toThrow(/bare\.js:1: .*relative.*'fflate'/);
    expect(() => bundle({ entry: 'dynamic.js', srcDir: errors })).toThrow(/dynamic\.js:2: .*import\(\)/);
    expect(() => bundle({ entry: 'multiline.js', srcDir: errors })).toThrow(/multiline\.js:1: .*one line/);
    expect(() => bundle({ entry: 'require.js', srcDir: errors })).toThrow(/require\.js:1: .*require\(\)/);
  });

  it('throws on import outside srcDir and on a missing module', () => {
    expect(() => bundle({ entry: 'entry.js', srcDir: join(FIXTURES, 'outside', 'src') }))
      .toThrow(/entry\.js:1: .*outside.*'\.\.\/helper\.js'/);
    expect(() => bundle({ entry: 'missing.js', srcDir: join(FIXTURES, 'errors') }))
      .toThrow(/Module not found: does-not-exist\.js \(imported from missing\.js\)/);
  });

  it('throws on unsupported module syntax', async () => {
    const dir = join(tmp, 'unsupported');
    await mkdir(dir, { recursive: true });
    const cases = {
      'destructure.js': 'export const { a } = {};\n',
      'indented.js': 'if (true) {\n  export const a = 1;\n}\n',
      'multi-export.js': 'const a = 1;\nexport {\n  a,\n};\n',
      'meta.js': 'export const url = import.meta.url;\n',
      'export-unknown.js': 'export { nope };\n',
      'dup-export.js': 'export const a = 1;\nexport { a };\n',
    };
    for (const [name, src] of Object.entries(cases)) {
      await writeFile(join(dir, name), src);
      expect(() => bundle({ entry: name, srcDir: dir }), name).toThrow(new RegExp(name.replace('.', '\\.')));
    }
  });

  it('throws on importing a name the module does not export', async () => {
    const dir = join(tmp, 'no-export');
    await mkdir(dir, { recursive: true });
    await writeFile(join(dir, 'entry.js'), "import { b } from './a.js';\n\nb();\n");
    await writeFile(join(dir, 'a.js'), 'export function a() {}\n');
    expect(() => bundle({ entry: 'entry.js', srcDir: dir })).toThrow(/entry\.js:1: a\.js does not export 'b'/);
  });

  it('runs the entry module without binding it (no unused __pds_m const)', () => {
    const code = graph();
    const entry = code.slice(code.indexOf('// module: entry.js'));
    expect(entry).toMatch(/^\/\/ module: entry\.js\n\(function \(\) \{\n/);
    expect(entry).not.toMatch(/const __pds_m\d+ = /);
    expect(code.match(/^const __pds_m\d+ = /gm)).toHaveLength(5);
  });

  // E2-IN4: `import './x.js'` alone must not leave an unused `const __pds_mN` behind.
  it('side-effect-only module is emitted without const binding', () => {
    const code = graph();
    const block = code.slice(code.indexOf('// module: side-effect.js'), code.indexOf('// module: entry.js'));
    expect(block).toMatch(/^\/\/ module: side-effect\.js\n\(function \(\) \{\n/);
    expect(block).not.toMatch(/const __pds_m\d+ = /);
    expect(run(code).out).toContain('side effect');
  });

  it('module used by named import keeps binding', async () => {
    const code = graph();
    for (const name of ['log.js', 'counter.js', 'util.js', 'constants.js', 'reexport.js']) {
      expect(code, name).toMatch(new RegExp(`// module: ${name.replace('.', '\\.')}\nconst __pds_m\\d+ = \\(function \\(\\) \\{`));
    }
    // Imported for side effect in one place and by name in another: still bound.
    const dir = join(tmp, 'mixed-side-effect');
    await mkdir(dir, { recursive: true });
    await writeFile(join(dir, 'entry.js'), "import './b.js';\nimport { a } from './a.js';\n\nglobalThis.__out.push(a);\n");
    await writeFile(join(dir, 'b.js'), "import './a.js';\n\nglobalThis.__out.push('b');\n");
    await writeFile(join(dir, 'a.js'), "export const a = 'a';\n");
    const mixed = bundle({ entry: 'entry.js', srcDir: dir });
    expect(mixed).toMatch(/\/\/ module: a\.js\nconst __pds_m0 = /);
    expect(mixed).toMatch(/\/\/ module: b\.js\n\(function \(\) \{/);
    expect(run(mixed).out).toEqual(['b', 'a']);
  });

  // Loading ESLint and its config takes 6–8 s on a Windows drive mounted in WSL (/mnt/c); the default 5 s timeout is too short there.
  it('ESLint no-unused-vars passes on a bundle with side-effect import', async () => {
    const { ESLint } = await import('eslint');
    const root = fileURLToPath(new URL('../../', import.meta.url));
    const eslint = new ESLint({ cwd: root });
    const [result] = await eslint.lintText(graph(), { filePath: join(root, 'src', 'content', 'main-world.js') });
    expect(result.messages.filter((m) => m.ruleId === 'no-unused-vars').map((m) => `${m.line}: ${m.message}`)).toEqual([]);
   }, ESLINT_TIMEOUT_MS);

  it('real bundles pass eslint with the project config (no exceptions for generated code)', async () => {
    const { ESLint } = await import('eslint');
    const root = fileURLToPath(new URL('../../', import.meta.url));
    const eslint = new ESLint({ cwd: root });
    for (const { out, entry } of BUNDLES) {
      const code = bundle({ entry, srcDir: join(root, 'src') });
      const [result] = await eslint.lintText(code, { filePath: join(root, 'src', out) });
      expect(result.messages.map((m) => `${m.line}: ${m.ruleId} ${m.message}`), out).toEqual([]);
    }
   }, ESLINT_TIMEOUT_MS);

  it('throws SyntaxError on duplicate top-level names within one module', async () => {
    const dir = join(tmp, 'dup');
    await mkdir(dir, { recursive: true });
    await writeFile(join(dir, 'entry.js'), 'const twice = 1;\nconst twice = 2;\n');
    expect(() => bundle({ entry: 'entry.js', srcDir: dir })).toThrow(SyntaxError);
  });
});

describe('generateAll', () => {
  async function project(name) {
    const root = join(tmp, name);
    await mkdir(join(root, 'src', 'page'), { recursive: true });
    for (const { entry } of BUNDLES) {
      await writeFile(join(root, 'src', entry), `globalThis.__out?.push(${JSON.stringify(entry)});\n`);
    }
    // E4-T3a: the viewer page is generated too (tests in gen-viewer.test.js).
    await mkdir(join(root, 'src', 'viewer'), { recursive: true });
    await writeFile(join(root, 'src', 'viewer', 'viewer.html'), '<meta content="{{CSP}}"><style></style><script>{{SCRIPT}}</script>\n');
    await writeFile(join(root, 'src', 'viewer', 'viewer-entry.js'), 'globalThis.__out?.push(1);\n');
    return root;
  }

  it('maps page entries to content and standalone bundles', () => {
    expect(BUNDLES).toEqual([
      { out: 'content/main-world.js', entry: 'page/main-entry.js' },
      { out: 'content/isolated-world.js', entry: 'page/isolated-entry.js' },
      { out: 'standalone/console-snapshot.js', entry: 'page/console-entry.js' },
    ]);
  });

  it('writes all bundles, then check mode reports nothing stale', async () => {
    const root = await project('gen-ok');
    expect(await generateAll({ root })).toEqual({ written: [...BUNDLES, ...HTML_BUNDLES].map((b) => b.out), stale: [] });
    expect(await generateAll({ root, check: true })).toEqual({ written: [], stale: [] });
    const main = await readFile(join(root, 'src', 'content', 'main-world.js'), 'utf8');
    expect(run(main).out).toEqual(['page/main-entry.js']);
  });

  it('check mode reports stale output without writing', async () => {
    const root = await project('gen-stale');
    await generateAll({ root });
    const target = join(root, 'src', 'content', 'isolated-world.js');
    await writeFile(target, '// hand edit\n');
    expect(await generateAll({ root, check: true })).toEqual({ written: [], stale: ['content/isolated-world.js'] });
    expect(await readFile(target, 'utf8')).toBe('// hand edit\n');
  });

  it('fails with the entry name when an entry module is missing', async () => {
    const root = await project('gen-missing');
    await rm(join(root, 'src', 'page', 'console-entry.js'));
    await expect(generateAll({ root })).rejects.toThrow(/Missing entry module: src\/page\/console-entry\.js/);
  });
});

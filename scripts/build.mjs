// Per-target build (design D3, D4): src/ -> dist/chrome, dist/firefox.
// Each target gets the merged manifest plus exactly the files reachable from it,
// copied byte for byte. Output depends only on file contents, so two builds are identical (AC-4.1).
//
// CLI: `node scripts/build.mjs` builds into dist/ and prints each target's size in KB.
// `--config <file>` (or PDS_CONFIG=<file>) builds the developer configuration into dist/<target>/lib/dev-config.js
// for both targets (E4 D5); without it nothing is read implicitly and the source module is copied as is.

import { copyFile, mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { mergeManifest } from './lib/manifest.mjs';
import { collectReachable } from './lib/reachability.mjs';
import { sanitizeDevConfig } from '../src/lib/dev-options.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const readJson = async (file) => JSON.parse(await readFile(file, 'utf8'));

// The module replaced by --config, relative to the extension root.
const DEV_CONFIG_MODULE = 'lib/dev-config.js';
const MAX_NAME_IN_HEADER = 100;

/**
 * Text of the generated dev-config.js: only sanitized rule names (DEFAULT_RULES) reach it, so the module can hold
 * nothing but a frozen literal. `sourceName` is the config's base name, never its local path.
 * @param {unknown} config
 * @param {string} sourceName
 */
export function devConfigModule(config, sourceName) {
  const { disabledRules } = sanitizeDevConfig(config);
  // A line break would end the comment; control and line-separator characters become spaces.
  const name = [...String(sourceName).slice(0, MAX_NAME_IN_HEADER)]
    .map((ch) => (ch < ' ' || ch === '\u007f' || ch === '\u2028' || ch === '\u2029' ? ' ' : ch))
    .join('')
    .replace(/ {2,}/g, ' ');
  return `// GENERATED by scripts/build.mjs from ${name}\n` +
    `export const BUILT_IN_DEV_CONFIG = Object.freeze(${JSON.stringify({ disabledRules })});\n`;
}

// Reads and checks the --config file: unreadable or invalid JSON fails the build naming the file; entries that the
// extension would ignore (AC-6.3) only produce a warning.
async function loadDevConfig(file, warn) {
  let raw;
  try {
    raw = JSON.parse(await readFile(file, 'utf8'));
  } catch (error) {
    throw new Error(`Developer config ${file}: ${error.message}`, { cause: error });
  }
  const { ignored } = sanitizeDevConfig(raw);
  if (ignored.length) warn(`Developer config ${basename(file)}: ignored ${ignored.join(', ')}`);
  return devConfigModule(raw, basename(file));
}

/**
 * Builds every target into `<outDir>/<target>/`, removing previous output first.
 * @param {{ srcDir?: string, outDir?: string, targets?: string[], devConfigPath?: string, warn?: (msg: string) => void }} [options]
 *   `devConfigPath`: developer configuration built into every target's lib/dev-config.js (E4 D5).
 * @returns {Promise<Record<string, string[]>>} per target: sorted POSIX paths, manifest.json included
 */
export async function build({
  srcDir = join(ROOT, 'src'),
  outDir = join(ROOT, 'dist'),
  targets = ['chrome', 'firefox'],
  devConfigPath,
  warn = (msg) => console.warn(msg),
} = {}) {
  srcDir = resolve(srcDir);
  outDir = resolve(outDir);
  const base = await readJson(join(srcDir, 'manifest.base.json'));
  // One generated text for every target, so Chrome and Firefox get the same configuration (AC-6.1).
  const devConfig = devConfigPath === undefined ? undefined : await loadDevConfig(resolve(devConfigPath), warn);
  const result = {};

  for (const target of targets) {
    const overlay = await readJson(join(srcDir, `manifest.${target}.json`));
    const manifest = mergeManifest(base, overlay);
    // Walk the source with the merged manifest, so a bad reference fails before anything is written.
    const files = await collectReachable(srcDir, { manifest });
    if (devConfig !== undefined && !files.includes(DEV_CONFIG_MODULE)) {
      throw new Error(`Developer config given, but ${DEV_CONFIG_MODULE} is not part of the ${target} build`);
    }

    const targetDir = join(outDir, target);
    await rm(targetDir, { recursive: true, force: true });
    await mkdir(targetDir, { recursive: true });
    await writeFile(join(targetDir, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
    for (const rel of files) {
      const to = join(targetDir, ...rel.split('/'));
      await mkdir(dirname(to), { recursive: true });
      if (devConfig !== undefined && rel === DEV_CONFIG_MODULE) await writeFile(to, devConfig);
      else await copyFile(join(srcDir, ...rel.split('/')), to);
    }
    result[target] = ['manifest.json', ...files].sort();
  }
  return result;
}

async function dirSize(dir, files) {
  let total = 0;
  for (const rel of files) total += (await stat(join(dir, ...rel.split('/')))).size;
  return total;
}

/**
 * CLI arguments → build options. Only an explicit `--config` / PDS_CONFIG selects a configuration file.
 * @param {string[]} argv arguments after the script name
 * @param {Record<string, string | undefined>} env
 * @returns {{ devConfigPath: string | undefined }}
 */
export function cliOptions(argv, env) {
  let config;
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--config') {
      config = argv[++i];
      if (!config) throw new Error('--config needs a file name');
    } else if (arg.startsWith('--config=')) {
      config = arg.slice('--config='.length);
      if (!config) throw new Error('--config needs a file name');
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }
  config ??= env.PDS_CONFIG || undefined;
  return { devConfigPath: config === undefined ? undefined : resolve(config) };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const outDir = join(ROOT, 'dist');
  try {
    const { devConfigPath } = cliOptions(process.argv.slice(2), process.env);
    const result = await build({ outDir, devConfigPath });
    for (const [target, files] of Object.entries(result)) {
      const kb = (await dirSize(join(outDir, target), files)) / 1024;
      console.log(`dist/${target}: ${files.length} files, ${kb.toFixed(1)} KB`);
    }
  } catch (error) {
    console.error(`Build failed: ${error.message}`);
    process.exitCode = 1;
  }
}

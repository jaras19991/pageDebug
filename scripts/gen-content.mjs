// Classic-script bundles from the ES modules in src/page/ (E1 D6). Content scripts cannot be
// modules, and every top-level declaration of a classic MAIN-world script becomes a page global,
// so each bundle is one IIFE: every module body runs in its own function scope inside it and
// exposes its exports as a frozen object; imports become `const` bindings from those objects.
//
// Deliberately line-based, not a parser. Only the subset listed below is accepted; anything else
// that looks like module syntax is an error, never a silent pass-through:
//   import './x.js';                        import { a, b as c } from './x.js';
//   import d from './x.js';                 import d, { a } from './x.js';
//   import * as ns from './x.js';           import d, * as ns from './x.js';
//   export function|async function|function*|class|const|let|var <name> …   (one name per statement)
//   export default function|class <name> …  export default <expression>
//   export { a, b as c };                   export { a, b as default } from './x.js';
//   export * from './x.js';                 export * as ns from './x.js';
// Each import/export statement sits on one line starting at column 0. Specifiers are relative,
// end in .js and stay inside srcDir. No import(), import.meta or require() anywhere (also not in
// comments or strings). No cycles. Exported values are a snapshot taken when the module finishes
// evaluating (no live bindings). Output is LF-only and depends only on the sources.
//
// CLI: `node scripts/gen-content.mjs [--check]` writes (or verifies) src/content/*.js and
// src/standalone/console-snapshot.js. Do not edit the generated files by hand.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import vm from 'node:vm';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const HEADER = '// GENERATED by scripts/gen-content.mjs — do not edit';

/** Output (relative to src/) ← entry module (relative to src/). All entries live in src/page/. */
export const BUNDLES = [
  { out: 'content/main-world.js', entry: 'page/main-entry.js' },
  { out: 'content/isolated-world.js', entry: 'page/isolated-entry.js' },
  { out: 'standalone/console-snapshot.js', entry: 'page/console-entry.js' },
];

const ID = String.raw`[A-Za-z_$][\w$]*`;
const SPEC = String.raw`(['"])([^'"]+)\2`; // capture groups: quote, specifier
const END = String.raw`\s*;?\s*(?://.*)?$`;
const DEFAULT_LOCAL = '__pds_default';

const RE = {
  importSide: new RegExp(String.raw`^import\s*${SPEC.replace('\\2', '\\1')}${END}`),
  importFrom: new RegExp(String.raw`^import\s+(.+?)\s+from\s*${SPEC}${END}`),
  exportDecl: new RegExp(String.raw`^export\s+((?:async\s+)?function\b\s*\*?\s*|class\s+|(?:const|let|var)\s+)(${ID})`),
  exportDefaultNamed: new RegExp(String.raw`^export\s+default\s+((?:async\s+)?function\b\s*\*?\s*|class\s+)(${ID})`),
  exportDefault: /^export\s+default\s+/,
  exportListFrom: new RegExp(String.raw`^export\s*\{([^{}]*)\}\s*from\s*${SPEC}${END}`),
  exportStar: new RegExp(String.raw`^export\s*\*\s*(?:as\s+(${ID})\s+)?from\s*${SPEC}${END}`),
  exportList: new RegExp(String.raw`^export\s*\{([^{}]*)\}${END}`),
};

function fail(where, message) {
  throw new Error(`${where}: ${message}`);
}

// `a, b as c` → [{ name: 'a', as: 'a' }, { name: 'b', as: 'c' }]. Trailing comma allowed.
function parseSpecList(text, where) {
  return text.split(',').map((s) => s.trim()).filter(Boolean).map((s) => {
    const m = new RegExp(String.raw`^(${ID})(?:\s+as\s+(${ID}))?$`).exec(s);
    if (!m) fail(where, `unsupported specifier '${s}'`);
    return { name: m[1], as: m[2] ?? m[1] };
  });
}

// Import clause between `import` and `from`.
function parseImportClause(clause, where) {
  const m = new RegExp(String.raw`^(?:(${ID})\s*(?:,\s*|$))?(?:\*\s*as\s+(${ID})|\{([^{}]*)\})?$`).exec(clause.trim());
  if (!m || (!m[1] && !m[2] && m[3] === undefined)) fail(where, `unsupported import clause '${clause.trim()}'`);
  const named = m[3] === undefined ? [] : parseSpecList(m[3], where);
  if (m[1]) named.unshift({ name: 'default', as: m[1] });
  return { named, namespace: m[2] ?? null };
}

function declares(body, name) {
  const n = name.replace(/\$/g, '\\$');
  return new RegExp(String.raw`(?:\bfunction\b\s*\*?\s*|\bclass\s+|\b(?:const|let|var)\s+)${n}(?![\w$])`).test(body);
}

/**
 * Bundles `entry` and its relative imports into one classic IIFE script.
 * @param {{ entry: string, srcDir?: string, banner?: string, outFile?: string }} options
 *   `entry` is relative to `srcDir` (default src/page). With `outFile` the result is also written there.
 * @returns {string} the bundle source
 */
export function bundle({ entry, srcDir = join(ROOT, 'src', 'page'), banner = HEADER, outFile } = {}) {
  const base = resolve(srcDir);
  const rel = (file) => relative(base, file).split(sep).join('/');
  const modules = new Map(); // abs path → parsed module, in evaluation order once done
  const visiting = [];

  function resolveSpec(spec, from, where) {
    if (!/^\.\.?\//.test(spec)) fail(where, `import specifier must be relative ('./' or '../'), got '${spec}'`);
    if (!spec.endsWith('.js')) fail(where, `import specifier must end in .js, got '${spec}'`);
    const file = resolve(dirname(from), spec);
    const r = relative(base, file);
    if (r.startsWith('..') || isAbsolute(r)) fail(where, `import resolves outside srcDir: '${spec}'`);
    return file;
  }

  function load(file, importer) {
    if (modules.has(file)) return modules.get(file);
    const at = visiting.indexOf(file);
    if (at !== -1) throw new Error(`Import cycle: ${[...visiting, file].map(rel).join(' -> ')}`);
    if (!existsSync(file)) {
      throw new Error(`Module not found: ${rel(file)}${importer ? ` (imported from ${rel(importer)})` : ''}`);
    }
    visiting.push(file);
    const name = rel(file);
    const lines = readFileSync(file, 'utf8').replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n').split('\n');
    const prologue = []; // import bindings, hoisted to the top of the module scope
    const body = [];
    const exports = []; // [exportedName, expression]
    const localExports = []; // names that must be declared in this module
    const addExport = (as, expr, where) => {
      if (exports.some(([n]) => n === as)) fail(where, `duplicate export '${as}'`);
      exports.push([as, expr]);
    };
    const dep = (spec, where) => load(resolveSpec(spec, file, where), file);

    lines.forEach((line, i) => {
      const where = `${name}:${i + 1}`;
      if (/\bimport\s*\(/.test(line)) fail(where, 'dynamic import() is not supported');
      if (/\bimport\s*\.\s*meta\b/.test(line)) fail(where, 'import.meta is not supported');
      if (/\brequire\s*\(/.test(line)) fail(where, 'require() is not supported');
      if (/^\s+(?:import|export)\b(?!\s*[.:=(])/.test(line)) fail(where, 'import/export must start at column 0');

      if (/^import\b/.test(line)) {
        let m = RE.importSide.exec(line);
        if (m) { dep(m[2], where); return; }
        m = RE.importFrom.exec(line);
        if (!m) fail(where, "import must fit on one line: import … from './x.js';");
        const target = dep(m[3], where);
        const { named, namespace } = parseImportClause(m[1], where);
        for (const { name: n } of named) {
          if (!target.exportNames.includes(n)) fail(where, `${target.name} does not export '${n}'`);
        }
        if (named.length) {
          const parts = named.map(({ name: n, as }) => (n === as ? n : `${n}: ${as}`));
          prologue.push(`const { ${parts.join(', ')} } = ${target.id};`);
        }
        if (namespace) prologue.push(`const ${namespace} = ${target.id};`);
        return;
      }

      if (/^export\b/.test(line)) {
        let m = RE.exportDefaultNamed.exec(line);
        if (m) {
          addExport('default', m[2], where);
          body.push(line.replace(RE.exportDefault, ''));
          return;
        }
        if (RE.exportDefault.test(line)) {
          addExport('default', DEFAULT_LOCAL, where);
          body.push(line.replace(RE.exportDefault, `const ${DEFAULT_LOCAL} = `));
          return;
        }
        m = RE.exportDecl.exec(line);
        if (m) {
          addExport(m[2], m[2], where);
          body.push(line.replace(/^export\s+/, ''));
          return;
        }
        m = RE.exportListFrom.exec(line);
        if (m) {
          const target = dep(m[3], where);
          for (const { name: n, as } of parseSpecList(m[1], where)) {
            if (!target.exportNames.includes(n)) fail(where, `${target.name} does not export '${n}'`);
            addExport(as, `${target.id}.${n}`, where);
          }
          return;
        }
        m = RE.exportStar.exec(line);
        if (m) {
          const target = dep(m[3], where);
          if (m[1]) addExport(m[1], target.id, where);
          else for (const n of target.exportNames.filter((x) => x !== 'default')) addExport(n, `${target.id}.${n}`, where);
          return;
        }
        m = RE.exportList.exec(line);
        if (m) {
          for (const { name: n, as } of parseSpecList(m[1], where)) {
            addExport(as, n, where);
            localExports.push([n, where]);
          }
          return;
        }
        fail(where, 'unsupported export form (one line; one declared name per export statement)');
      }
      body.push(line);
    });

    const source = body.join('\n');
    for (const [n, where] of localExports) {
      if (!declares(source, n) && !prologue.some((p) => new RegExp(String.raw`[{\s,:]${n.replace(/\$/g, '\\$')}[\s,}]`).test(p))) {
        fail(where, `exported name '${n}' is not declared in this module`);
      }
    }

    visiting.pop();
    const mod = {
      name,
      id: `__pds_m${modules.size}`,
      exportNames: exports.map(([n]) => n),
      code: [
        `// module: ${name}`,
        // The entry (loaded last, nothing imports it) only runs: binding it would be an unused const.
        importer ? `const __pds_m${modules.size} = (function () {` : '(function () {',
        ...prologue,
        source.replace(/\n+$/, ''),
        `return Object.freeze({ ${exports.map(([n, e]) => `${n}: ${e}`).join(', ')} });`,
        '})();',
      ].join('\n'),
    };
    modules.set(file, mod);
    return mod;
  }

  load(resolve(base, entry), null);
  const code = `${banner}\n(function () {\n  'use strict';\n\n${[...modules.values()].map((m) => m.code).join('\n\n')}\n})();\n`;
  new vm.Script(code, { filename: outFile ?? entry }); // syntax check only; throws SyntaxError
  if (outFile) {
    mkdirSync(dirname(outFile), { recursive: true });
    writeFileSync(outFile, code);
  }
  return code;
}

/**
 * Generates every bundle from BUNDLES under `root`/src, or with `check` only compares.
 * @param {{ root?: string, check?: boolean }} [options]
 * @returns {Promise<{ written: string[], stale: string[] }>} outputs (relative to src/) written or out of date
 */
export async function generateAll({ root = ROOT, check = false } = {}) {
  const src = join(root, 'src');
  // Imports may reach all of src/ (console-entry.js uses ../lib/package.js); entries stay in src/page/.
  const srcDir = src;
  for (const { entry } of BUNDLES) {
    if (!existsSync(join(src, entry))) throw new Error(`Missing entry module: src/${entry} (created in E1-T15/T7)`);
  }
  const results = BUNDLES.map(({ out, entry }) => {
    const code = bundle({ entry: relative(srcDir, join(src, entry)), srcDir });
    const file = join(src, out);
    const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
    return { out, code, file, changed: current !== code };
  });
  const changed = results.filter((r) => r.changed);
  if (check) return { written: [], stale: changed.map((r) => r.out) };
  for (const { file, code } of changed) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, code);
  }
  return { written: changed.map((r) => r.out), stale: [] };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const check = process.argv.includes('--check');
  try {
    const { written, stale } = await generateAll({ check });
    if (check && stale.length) {
      console.error(`Stale generated files (run \`npm run gen\`): ${stale.map((f) => `src/${f}`).join(', ')}`);
      process.exitCode = 1;
    } else if (check) {
      console.log('Generated files are up to date.');
    } else {
      console.log(written.length ? written.map((f) => `wrote src/${f}`).join('\n') : 'Generated files are up to date.');
    }
  } catch (error) {
    console.error(`gen-content: ${error.message}`);
    process.exitCode = 1;
  }
}
